# Builds ../zh.js from zh.txt, zhverbs.txt, zhwords.txt, zhsit.txt. Run from the app root: python3 src/build_zh.py
import json,re,collections
FW=str.maketrans({'?':'？','!':'！',',':'，'})
fw=lambda s:s.translate(FW)  # full-width punctuation for the Chinese-script field only
def phrases(f):
  out=collections.OrderedDict()
  for ln in open(f,encoding='utf8'):
    ln=ln.rstrip('\n')
    if not ln:continue
    if ln[0]=='@':lv,t=ln[1:].split();out.setdefault(lv,collections.OrderedDict())[t]=[];cur=out[lv][t];continue
    x=ln.split('|');assert len(x)==5,x;x[0]=fw(x[0]);cur.append(x)
  return out
P=phrases('src/zh.txt')
DATA={t:[a[:4] for a in v] for t,v in P['beg'].items()}
PRON={a[0]:a[4] for v in P['beg'].values() for a in v}
LEV={lv:P[lv] for lv in('int','adv')}
def verbs(f):
  V=[]
  for ln in open(f,encoding='utf8'):
    ln=ln.rstrip('\n');t=ln.startswith('*');x=ln.lstrip('*').split('|');assert len(x)==11,x[0]
    sp=lambda s:s.split(';') if s else None
    ex=x[9].split(';');ex[0]=fw(ex[0])
    V.append({"d":x[0],"r":x[1],"en":x[2],"irr":x[3],"f":dict(zip("abcde",[sp(s) for s in x[4:9]])),"ex":ex,"pr":x[10],"trip":t})
  return V
def words(f):
  C=[]
  for ln in open(f,encoding='utf8'):
    ln=ln.rstrip('\n')
    if not ln:continue
    if ln[0]=='@':k,n=ln[1:].split(' ',1);C.append({"k":k,"n":n,"w":[]});continue
    t=ln.startswith('*');x=ln.lstrip('*').split('|');assert len(x)==5,x
    nat,rom,en,pr,note=x;C[-1]["w"].append({"nat":nat,"kana":"","rom":rom,"en":en,"pr":pr,"note":note,"trip":t})
  return C
def sits(f):
  L=[]
  for ln in open(f,encoding='utf8'):
    ln=ln.rstrip('\n')
    if not ln or ln.startswith('# '):continue
    if ln[0]=='#':i,em,t,tr=ln[1:].split('|');L.append({"id":i,"em":em,"t":t,"steps":[],**({"trip":True} if tr=='1' else {})});continue
    k,body=ln.split(' ',1);x=body.split('|');x[0]=fw(x[0])
    if k=='S':assert len(x)==3,x;L[-1]["steps"].append({"s":x,"o":[]})
    else:assert k=='O' and len(x)==4,x;L[-1]["steps"][-1]["o"].append(x)
  for c in L:
    for s in c["steps"]:assert len(s["o"])==3,(c["id"],s["s"])
  return L
VB=verbs('src/zhverbs.txt');W=words('src/zhwords.txt');SI=sits('src/zhsit.txt')
j=lambda o:json.dumps(o,ensure_ascii=False)
open('zh.js','w',encoding='utf8').write("// Mandarin Chinese (zh-CN). Generated by src/build_zh.py from src/zh*.txt. Do not edit by hand.\n"
 f"DATA.zh={j(DATA)};\nPRON.zh={j(PRON)};\nLEVELS.zh={j(LEV)};\nSIT.zh={j(SI)};\n"
 'VFORMS.zh=["Doing now (在…)","Did it (…了)","Not (不…)","Want to (想…)","Please (请…)"];\n'
 f"VERBS.zh={j(VB)};\nWORDS.zh={j(W)};\n")
for lv in P:print(lv,{t:len(v) for t,v in P[lv].items()},sum(len(v) for v in P[lv].values()))
print('verbs',len(VB),'trip',sum(v['trip'] for v in VB))
print('words',[(c['k'],len(c['w'])) for c in W],sum(len(c['w']) for c in W))
print('scenes',[(c['id'],len(c['steps'])) for c in SI])
